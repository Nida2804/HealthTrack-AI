"""
AI Service module for HealthTrack AI – Patient Health Management System.
Integrates with Google Gemini API via the official `google-genai` Python SDK
to generate cautious, educational health remarks from patient blood test values.
"""

import os
import logging
from typing import Optional
from dotenv import load_dotenv

# Load environment variables from .env file
load_dotenv()

logger = logging.getLogger(__name__)

# Configured Gemini model ID
DEFAULT_GEMINI_MODEL = "gemini-3.5-flash-lite"

# Mandatory medical disclaimer appended to all AI evaluations
MANDATORY_DISCLAIMER = (
    "\n\n**Medical Disclaimer:** "
    "These remarks are generated by an AI assistant solely for educational and informational purposes. "
    "They DO NOT constitute a medical diagnosis, clinical judgment, prognosis, or medical treatment plan. "
    "Always consult a qualified, licensed healthcare professional or physician for interpretation of laboratory results, "
    "medical evaluations, and personal health decisions."
)


def get_gemini_api_key(override_key: Optional[str] = None) -> Optional[str]:
    """
    Retrieve Gemini API key from runtime override,
    environment variables, or Streamlit secrets.
    """
    if override_key and override_key.strip():
        return override_key.strip()

    key = os.getenv("GEMINI_API_KEY", "").strip()
    if key:
        return key

    try:
        import streamlit as st
        key = st.secrets.get("GEMINI_API_KEY", "").strip()
        if key:
            return key
    except Exception:
        pass

    return None


def is_gemini_configured(override_key: Optional[str] = None) -> bool:
    """
    Check if a Gemini API key is currently available in the environment or session.
    """
    return bool(get_gemini_api_key(override_key))


def generate_educational_fallback_remarks(
    glucose: float, haemoglobin: float, cholesterol: float, note: Optional[str] = None
) -> str:
    """
    Generate deterministic, cautious educational remarks based on established
    clinical laboratory reference intervals when live AI is unavailable or unconfigured.
    Preserves exact user input values and states reference ranges.
    """
    remarks = []

    # Educational evaluation of Fasting Glucose (typical reference 70 - 99 mg/dL)
    if glucose < 70.0:
        remarks.append(
            f"• **Fasting Glucose ({glucose} mg/dL):** Below standard fasting reference (70–99 mg/dL). "
            "Lower levels may occur with extended fasting, rigorous exercise, or metabolic factors."
        )
    elif 70.0 <= glucose <= 99.0:
        remarks.append(
            f"• **Fasting Glucose ({glucose} mg/dL):** Within standard fasting reference range (70–99 mg/dL)."
        )
    elif 100.0 <= glucose <= 125.0:
        remarks.append(
            f"• **Fasting Glucose ({glucose} mg/dL):** Slightly elevated above standard fasting reference (100–125 mg/dL range). "
            "Often warrants lifestyle assessment, nutritional review, and physician follow-up."
        )
    else:
        remarks.append(
            f"• **Fasting Glucose ({glucose} mg/dL):** Significantly elevated relative to standard fasting guidelines (≥126 mg/dL). "
            "A comprehensive clinical evaluation and repeat testing under medical supervision are advised."
        )

    # Educational evaluation of Haemoglobin (typical adult reference 12.0 - 17.5 g/dL)
    if haemoglobin < 12.0:
        remarks.append(
            f"• **Haemoglobin ({haemoglobin} g/dL):** Below standard reference intervals (typically 12.0–17.5 g/dL). "
            "Lower concentrations can be associated with nutritional factors or reduced red cell indices."
        )
    elif 12.0 <= haemoglobin <= 17.5:
        remarks.append(
            f"• **Haemoglobin ({haemoglobin} g/dL):** Within standard adult reference range (12.0–17.5 g/dL)."
        )
    else:
        remarks.append(
            f"• **Haemoglobin ({haemoglobin} g/dL):** Elevated relative to typical adult ranges (>17.5 g/dL). "
            "Can reflect dehydration, physiological adaptation, or other clinical factors requiring doctor evaluation."
        )

    # Educational evaluation of Total Cholesterol (typical reference < 200 mg/dL)
    if cholesterol < 200.0:
        remarks.append(
            f"• **Total Cholesterol ({cholesterol} mg/dL):** Within desirable lipid target levels (<200 mg/dL)."
        )
    elif 200.0 <= cholesterol <= 239.0:
        remarks.append(
            f"• **Total Cholesterol ({cholesterol} mg/dL):** In the borderline elevated range (200–239 mg/dL). "
            "Cardiovascular risk factor assessment and dietary evaluation are commonly recommended."
        )
    else:
        remarks.append(
            f"• **Total Cholesterol ({cholesterol} mg/dL):** Elevated above recommended targets (≥240 mg/dL). "
            "A full lipid fractionation panel (LDL, HDL, Triglycerides) and consultation with a doctor are recommended."
        )

    # Header and context
    header = "### 📋 Clinical Educational Assessment\n"
    if note:
        header += f"*{note}*\n\n"

    body = "\n".join(remarks)
    general_guidance = (
        "\n\n**General Wellness Notes:**\n"
        "- Maintain balanced nutrition, adequate hydration, and regular physical activity.\n"
        "- Blood parameters fluctuate based on fasting status, time of day, and individual health factors."
    )

    return header + body + general_guidance + MANDATORY_DISCLAIMER


def generate_health_remarks(
    full_name: str,
    date_of_birth: str,
    glucose: float,
    haemoglobin: float,
    cholesterol: float,
    api_key_override: Optional[str] = None,
) -> str:
    """
    Generate cautious, educational health remarks for a patient's blood test values
    using the Google Gemini API (via google-genai package).
    
    If the API key is not present or an error occurs during the API call,
    gracefully falls back to the deterministic clinical educational generator
    without interrupting the application workflow.
    """
    api_key = get_gemini_api_key(api_key_override)

    if not api_key:
        logger.info("GEMINI_API_KEY not found in environment; using standard educational reference mode.")
        return generate_educational_fallback_remarks(
            glucose=glucose,
            haemoglobin=haemoglobin,
            cholesterol=cholesterol,
            note="Generated in Standard Clinical Reference Mode (GEMINI_API_KEY environment variable is not configured).",
        )

    # Attempt to use the official google-genai SDK
    try:
        from google import genai
        from google.genai import types

        client = genai.Client(api_key=api_key)

        prompt = f"""
You are HealthTrack AI, a cautious and educational clinical assistant.
Analyze the following patient blood test values:

- Patient Name: {full_name}
- Date of Birth: {date_of_birth}
- Fasting Blood Glucose: {glucose} mg/dL
- Haemoglobin: {haemoglobin} g/dL
- Total Cholesterol: {cholesterol} mg/dL

STRICT CLINICAL SAFETY RULES:
1. Provide cautious, educational observations comparing these numbers against standard laboratory reference intervals:
   - Fasting Glucose: Normal 70-99 mg/dL, Impaired/Pre-diabetes 100-125 mg/dL, High >=126 mg/dL.
   - Haemoglobin: Normal adult 12.0-17.5 g/dL (varies by sex/age).
   - Total Cholesterol: Desirable <200 mg/dL, Borderline 200-239 mg/dL, High >=240 mg/dL.
2. DO NOT claim or imply a diagnosis of any disease (e.g., do NOT state "you have diabetes", "the patient is anemic", etc.).
3. Frame every comment objectively and cautiously using words like "indicates", "aligns with", "warrants discussion with a physician".
4. Suggest general lifestyle considerations (e.g., balanced dietary habits, hydration, exercise, routine medical checkups).
5. Always conclude with the exact text:
   "Medical Disclaimer: These remarks are provided for educational purposes only and do not constitute a medical diagnosis or treatment plan. Please consult a qualified healthcare professional for professional clinical advice."

Format the response with clean markdown headings and bullet points. Keep it professional, objective, and around 100-180 words.
"""

        # Generate health remarks using the configured Gemini model
        model_name = DEFAULT_GEMINI_MODEL
        response = client.models.generate_content(
            model=model_name,
            contents=prompt,
            config=types.GenerateContentConfig(
                temperature=0.2,  # Low temperature for factual, cautious, consistent remarks
                max_output_tokens=800,
            ),
        )
        generated_text = response.text.strip() if response.text else ""

        if not generated_text:
            raise ValueError("Empty response received from Gemini API.")

        # Ensure mandatory disclaimer is present in the final output
        if "Medical Disclaimer:" not in generated_text and "medical diagnosis" not in generated_text.lower():
            generated_text += MANDATORY_DISCLAIMER

        return generated_text

    except Exception as exc:
        logger.error("Gemini API call encountered an error: %s", exc)
        return generate_educational_fallback_remarks(
            glucose=glucose,
            haemoglobin=haemoglobin,
            cholesterol=cholesterol,
            note=f"Live AI remarks temporarily unavailable (API Notice: {str(exc)[:120]}...). Switched to Clinical Reference Mode.",
        )

